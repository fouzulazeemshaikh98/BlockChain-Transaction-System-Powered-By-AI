"""Trains the behavioural models used by POST /v1/risk/score.

    cd ai-engine
    ./.venv/Scripts/python scripts/train_risk_models.py

Writes:
    models/xgb_risk.joblib      - XGBoost supervised fraud classifier
    models/iso_forest.joblib    - Isolation Forest fitted on legitimate traffic only
    models/training_report.json - held-out metrics from THIS run

IMPORTANT - the training data is SYNTHETIC. It is generated below from simple
distributions (legitimate transfers vs phishing/scam-style transfers: large
amount spikes, high velocity, new receivers, odd hours). The metrics this
script prints describe how well the models separate those synthetic
distributions; they are NOT a measurement on real-world fraud data and must
not be reported as such. Swap generate_synthetic() for a real labelled
dataset (same 8 features, see ml/risk_features.py) to get meaningful numbers.
"""

import json
import sys
from pathlib import Path

import joblib
import numpy as np
from sklearn.ensemble import IsolationForest
from sklearn.metrics import accuracy_score, f1_score, precision_score, recall_score, roc_auc_score
from sklearn.model_selection import train_test_split
from xgboost import XGBClassifier

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ml.risk_features import FEATURE_NAMES, build_vector  # noqa: E402

OUT_DIR = ROOT / "models"
SEED = 42


def _legit(rng: np.random.Generator) -> list[float]:
    base = rng.lognormal(mean=6.0, sigma=1.2)  # typical transfer size, whole tokens
    history = list(base * rng.lognormal(0, 0.35, size=rng.integers(0, 12)))
    amount = base * rng.lognormal(0, 0.35)
    gas = rng.uniform(0.05, 40.0)
    gas_hist = list(gas * rng.lognormal(0, 0.25, size=rng.integers(0, 12)))
    return build_vector(
        amount_tokens=amount,
        recent_amounts_tokens=history,
        tx_count_last_hour=int(rng.poisson(0.8)),
        known_receiver=rng.random() < 0.75,
        gas_price_gwei=gas,
        recent_gas_gwei=gas_hist,
        calldata_bytes=68,
        hour_utc=int(np.clip(rng.normal(13, 3.5), 0, 23)),
    )


def _fraud(rng: np.random.Generator) -> list[float]:
    base = rng.lognormal(mean=6.0, sigma=1.2)
    history = list(base * rng.lognormal(0, 0.35, size=rng.integers(0, 12)))
    # Scam pattern: drain-style spike, burst of transfers, fresh receiver,
    # off-hours - but each signal is only present with some probability so
    # the classes overlap rather than being trivially separable.
    amount = base * (rng.uniform(4, 60) if rng.random() < 0.7 else rng.lognormal(0, 0.4))
    gas = rng.uniform(0.05, 40.0) * (rng.uniform(3, 20) if rng.random() < 0.25 else 1.0)
    gas_hist = list(rng.uniform(0.05, 40.0) * rng.lognormal(0, 0.25, size=rng.integers(0, 12)))
    return build_vector(
        amount_tokens=amount,
        recent_amounts_tokens=history,
        tx_count_last_hour=int(rng.poisson(6.0) if rng.random() < 0.6 else rng.poisson(1.0)),
        known_receiver=rng.random() < 0.15,
        gas_price_gwei=gas,
        recent_gas_gwei=gas_hist,
        calldata_bytes=68 if rng.random() < 0.85 else int(rng.integers(100, 400)),
        hour_utc=int(rng.integers(0, 6)) if rng.random() < 0.5 else int(rng.integers(0, 24)),
    )


def generate_synthetic(n_legit: int = 6000, n_fraud: int = 2000) -> tuple[np.ndarray, np.ndarray]:
    rng = np.random.default_rng(SEED)
    x = [_legit(rng) for _ in range(n_legit)] + [_fraud(rng) for _ in range(n_fraud)]
    y = [0] * n_legit + [1] * n_fraud
    return np.array(x, dtype=float), np.array(y, dtype=int)


def main() -> None:
    x, y = generate_synthetic()
    x_train, x_test, y_train, y_test = train_test_split(x, y, test_size=0.25, stratify=y, random_state=SEED)

    clf = XGBClassifier(
        n_estimators=300,
        max_depth=4,
        learning_rate=0.08,
        subsample=0.9,
        colsample_bytree=0.9,
        eval_metric="logloss",
        random_state=SEED,
    )
    clf.fit(x_train, y_train)

    iso = IsolationForest(n_estimators=200, contamination="auto", random_state=SEED)
    iso.fit(x_train[y_train == 0])  # unsupervised: learns "normal" only

    proba = clf.predict_proba(x_test)[:, 1]
    pred = (proba >= 0.5).astype(int)
    report = {
        "data": "SYNTHETIC - generated by scripts/train_risk_models.py, not real transactions",
        "features": FEATURE_NAMES,
        "train_size": int(len(y_train)),
        "test_size": int(len(y_test)),
        "xgboost_holdout": {
            "accuracy": round(float(accuracy_score(y_test, pred)), 4),
            "precision": round(float(precision_score(y_test, pred)), 4),
            "recall": round(float(recall_score(y_test, pred)), 4),
            "f1": round(float(f1_score(y_test, pred)), 4),
            "roc_auc": round(float(roc_auc_score(y_test, proba)), 4),
        },
        "isolation_forest_holdout_roc_auc": round(float(roc_auc_score(y_test, -iso.score_samples(x_test))), 4),
    }

    OUT_DIR.mkdir(exist_ok=True)
    joblib.dump(clf, OUT_DIR / "xgb_risk.joblib")
    joblib.dump(iso, OUT_DIR / "iso_forest.joblib")
    (OUT_DIR / "training_report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")

    print(json.dumps(report, indent=2))
    print(f"Saved models to {OUT_DIR}")


if __name__ == "__main__":
    main()
